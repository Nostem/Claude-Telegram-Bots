"""Build a Markdown review page for a group of cards, with each image beside its text.

Usage: python3 tools/build_review.py major   (or cups, swords, wands, pentacles)
Writes docs/review/<group>.md, which GitHub shows with the images inline.
"""
import sys
from pathlib import Path

import yaml

CARDS_DIR = Path("content/tarot/cards")
OUT_DIR = Path("docs/review")
TITLES = {"major": "Major Arcana", "cups": "Cups", "swords": "Swords", "wands": "Wands",
          "pentacles": "Pentacles"}


def card_section(card):
    c = card
    lines = [
        f"## {c['name']}",
        "",
        f'<img src="../../content/tarot/images/cards/{c["image"]}" width="220" align="right">',
        "",
        f"**Upright:** *{', '.join(c['keywords']['upright'])}*  ",
        f"{c['short']['upright']}",
        "",
        f"**Reversed:** *{', '.join(c['keywords']['reversed'])}*  ",
        f"{c['short']['reversed']}",
        "",
        f"**Yes/No:** {c['yes_no']} · **Element:** {c['correspondences'].get('element', '')}"
        f" · **Astrology:** {c['correspondences'].get('astrology', '')}",
        "",
        "### Upright meaning",
        c["meaning"]["upright"],
        "",
        "### Reversed meaning",
        c["meaning"]["reversed"],
        "",
        f"**Love:** {c['in_context']['love']}  ",
        f"**Work:** {c['in_context']['work']}  ",
        f"**Advice:** {c['in_context']['advice']}",
        "",
        "### Symbolism",
        *[f"- {s}" for s in c["symbolism"]],
        "",
        "### Reflection",
        *[f"- {q}" for q in c["reflection"]],
        "",
        "<details><summary>Waite, 1910</summary>",
        "",
        f"**Upright:** {c['waite_1910']['upright']}  ",
        f"**Reversed:** {c['waite_1910']['reversed']}",
        "",
        "</details>",
        "",
        '<br clear="right">',
        "",
        "---",
        "",
    ]
    return "\n".join(lines)


def main():
    group = sys.argv[1] if len(sys.argv) > 1 else "major"
    paths = sorted(CARDS_DIR.glob(f"{group}-*.yaml"))
    cards = [yaml.safe_load(p.read_text()) for p in paths]
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out = OUT_DIR / f"{group}.md"
    header = f"# Review: {TITLES[group]}\n\nGenerated by `tools/build_review.py` from the card files. Edit the YAML files, not this page.\n\n"
    out.write_text(header + "".join(card_section(c) for c in cards))
    print(f"{len(cards)} cards -> {out}")


if __name__ == "__main__":
    main()
